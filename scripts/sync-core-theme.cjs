// Generate identical theme adapters for the SPA and Flask Wiki; --check never writes.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const tokens = require(path.join(root, 'webapp/src/styles/themeTokens.json'));
const framework = fs.readFileSync(path.join(root, 'webapp/src/styles/coreComponents.css'), 'utf8');
let css = '/* Generated by scripts/sync-core-theme.cjs. Edit themeTokens.json/coreComponents.css. */\n';
for (const [mode, values] of Object.entries(tokens)) {
  const selector = mode === 'dark' ? 'html[data-kachhapa-ui="core"]' : 'html[data-kachhapa-ui="core"][data-theme="light"]';
  css += `${selector} {\n  color-scheme: ${mode};\n`;
  for (const [name, value] of Object.entries(values)) css += `  --${name}: ${value};\n`;
  for (const [name, key] of Object.entries({'primary':'accent','secondary':'secondary','link-color':'accent-2','link-hover-color':'accent-2','body-bg':'bg-app','body-color':'text-main','emphasis-color':'text-main','secondary-bg':'bg-surface-2','tertiary-bg':'bg-surface-3'})) {
    const rgb=values[key].slice(1).match(/../g).map(part=>parseInt(part,16)).join(',');
    css += `  --bs-${name}-rgb: ${rgb};\n`;
  }
  css += '}\n';
}
css += framework;
let failed = false;
for (const name of ['webapp/src/styles/coreTheme.css', 'Flask/static/kachhapa-theme.css']) {
  const target = path.join(root, name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== css) { process.stderr.write(`${name} is stale\n`); failed = true; }
  } else fs.writeFileSync(target, css);
}
const crypto=require('crypto');
const version=crypto.createHash('sha256').update(css).update(fs.readFileSync(path.join(root,'Flask/static/kachhapa-theme.js'))).digest('hex').slice(0,12);
const templatePath=path.join(root,'Flask/templates/base.html');
const template=fs.readFileSync(templatePath,'utf8');
const versioned=template.replace(/kachhapa-theme\.(css|js)(?:\?v=[a-f0-9]+)?/g, (_,ext)=>`kachhapa-theme.${ext}?v=${version}`);
if (process.argv.includes('--check')) {
  if(template!==versioned) { process.stderr.write('Wiki theme asset versions are stale\n'); failed=true; }
} else fs.writeFileSync(templatePath,versioned);
if (failed) process.exit(1);
